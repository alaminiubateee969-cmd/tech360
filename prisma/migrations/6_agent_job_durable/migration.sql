-- Durable, idempotent queue for governed agent inference jobs.
-- This additive table does not alter or delete existing customer or execution data.
CREATE TABLE `AgentJob` (
    `id` VARCHAR(191) NOT NULL,
    `idempotencyKey` VARCHAR(191) NOT NULL,
    `payloadHash` CHAR(64) NOT NULL,
    `taskType` VARCHAR(191) NOT NULL DEFAULT 'INFERENCE',
    `agentCode` VARCHAR(191) NOT NULL,
    `clientId` VARCHAR(191) NULL,
    `projectId` VARCHAR(191) NULL,
    `correlationId` VARCHAR(191) NOT NULL,
    `workflow` VARCHAR(191) NULL,
    `input` LONGTEXT NOT NULL,
    `contextNote` LONGTEXT NULL,
    `expectJson` BOOLEAN NOT NULL DEFAULT false,
    `status` VARCHAR(191) NOT NULL DEFAULT 'QUEUED',
    `approvalState` VARCHAR(191) NOT NULL DEFAULT 'NOT_REQUIRED',
    `requestedBy` VARCHAR(191) NULL,
    `approvedBy` VARCHAR(191) NULL,
    `approvedAt` DATETIME(3) NULL,
    `approvalNote` TEXT NULL,
    `attempts` INTEGER NOT NULL DEFAULT 0,
    `maxAttempts` INTEGER NOT NULL DEFAULT 3,
    `checkpoint` LONGTEXT NULL,
    `output` LONGTEXT NULL,
    `lastError` TEXT NULL,
    `availableAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `claimedBy` VARCHAR(191) NULL,
    `leaseUntil` DATETIME(3) NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL,
    `startedAt` DATETIME(3) NULL,
    `completedAt` DATETIME(3) NULL,

    UNIQUE INDEX `AgentJob_idempotencyKey_key`(`idempotencyKey`),
    UNIQUE INDEX `AgentJob_correlationId_key`(`correlationId`),
    INDEX `AgentJob_status_availableAt_createdAt_idx`(`status`, `availableAt`, `createdAt`),
    INDEX `AgentJob_status_leaseUntil_idx`(`status`, `leaseUntil`),
    INDEX `AgentJob_clientId_createdAt_idx`(`clientId`, `createdAt`),
    INDEX `AgentJob_agentCode_createdAt_idx`(`agentCode`, `createdAt`),
    INDEX `AgentJob_projectId_createdAt_idx`(`projectId`, `createdAt`),
    PRIMARY KEY (`id`),
    CONSTRAINT `AgentJob_agentCode_fkey` FOREIGN KEY (`agentCode`) REFERENCES `AiAgent`(`code`) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `AgentJob_clientId_fkey` FOREIGN KEY (`clientId`) REFERENCES `Client`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `AgentJob_projectId_fkey` FOREIGN KEY (`projectId`) REFERENCES `Project`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
