/**
 * TECH360 — structured data (schema.org / JSON-LD) for the public website.
 *
 * One module owns the entity identifiers and the node shapes so that the
 * homepage document and every crawlable sub-page emit the SAME `@id` values for
 * Organization, WebSite and WebPage. Duplicated or contradictory graphs are the
 * fastest way to lose rich-result eligibility, so this file must stay the only
 * place these nodes are constructed.
 *
 * Truthfulness rules enforced here (see docs/audit/TECH360-WEBSITE-FULL-AUDIT.md):
 *  - `sameAs` lists ONLY company-controlled, publicly reachable profiles. No
 *    social/directory URLs are invented; unverified handles are dropped.
 *  - No `aggregateRating`, `review`, `offers`, `price` or `availability` is ever
 *    emitted — TECH360 has no published prices, ratings or testimonials.
 *  - FAQPage markup exists only where the FAQ text is visibly rendered.
 *  - A valid schema type is not a claim of Google rich-result eligibility.
 *
 * Pure data — safe in the edge proxy and in the Node runtime.
 */

