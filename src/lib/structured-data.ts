/**
 * Page-level graph for a crawlable sub-page. Returns `null` when the path has no
 * public representation, so callers never emit a node for a private surface.
 */
export function pageGraph(pathname: string, meta: { title: string; description: string }) {
  const [section, slug] = pathname.replace(/^\/+/, '').split('/')

  if (section === 'services' && slug) {
    const service = SERVICES.find((s) => s.slug === slug)
    if (!service) return null
    // The Service entity for this slug is already defined once, in the site
    // graph (`SERVICE_NODES`). Re-declaring it here with different copy would
    // produce two contradictory nodes sharing one @id, so this page node
    // REFERENCES the existing entity instead of restating it.
    const serviceId = `${SITE_URL}/services/${slug}#service`
    return [
      {
        ...webPageNode({ path: `/services/${slug}`, name: meta.title, description: meta.description }),
        mainEntity: { '@id': serviceId },
      },
      breadcrumbNode([
        { name: 'Home', path: '/' },
        { name: 'Services', path: '/services' },
        { name: service.title, path: `/services/${slug}` },
      ]),
    ]
  }

  if (section === 'industries' && slug) {
    const industry = INDUSTRIES.find((i) => i.slug === slug)
    if (!industry) return null
    const rich = getIndustryBySlug(slug)
    return [
      webPageNode({ path: `/industries/${slug}`, name: meta.title, description: meta.description }),
      breadcrumbNode([
        { name: 'Home', path: '/' },
        { name: 'Industries', path: '/industries' },
        { name: industry.title, path: `/industries/${slug}` },
      ]),
      {
        '@type': 'Service',
        // Page-scoped @id: distinct from the site-wide service catalogue, so no
        // entity is ever defined twice with different content.
        '@id': `${SITE_URL}/industries/${slug}#service`,
        name: `${industry.title} software solutions`,
        description: rich?.data.hero.subhead || industry.description,
        url: `${SITE_URL}/industries/${slug}`,
        serviceType: `${industry.title} software`,
        provider: { '@id': ORG_ID },
        areaServed: 'Worldwide',
      },
    ]
  }

  if (section === 'legal' && slug) {
    const doc = LEGAL_DOCS.find((d) => d.slug === slug)
    if (!doc) return null
    return [
      webPageNode({ path: `/legal/${slug}`, name: doc.title, description: doc.summary }),
      breadcrumbNode([
        { name: 'Home', path: '/' },
        { name: 'Legal & Policies', path: '/legal' },
        { name: doc.title, path: `/legal/${slug}` },
      ]),
    ]
  }

  type PageNodeType = 'AboutPage' | 'ContactPage' | 'CollectionPage' | 'WebPage' | 'FAQPage'
  const simple: Record<string, { type: PageNodeType; trail: string }> = {
    '/about': { type: 'AboutPage', trail: 'About TECH360' },
    '/contact': { type: 'ContactPage', trail: 'Contact' },
    '/platform': { type: 'CollectionPage', trail: 'Company-in-a-Box Platform' },
    '/services': { type: 'CollectionPage', trail: 'Services' },
    '/industries': { type: 'CollectionPage', trail: 'Industries' },
    '/work': { type: 'CollectionPage', trail: 'Work' },
    '/work/projects': { type: 'CollectionPage', trail: 'System Scenarios' },
    '/work/case-studies': { type: 'CollectionPage', trail: 'Delivery Case Frameworks' },
    '/technologies': { type: 'WebPage', trail: 'Technologies' },
    '/process': { type: 'WebPage', trail: 'Delivery Process' },
    '/careers': { type: 'WebPage', trail: 'Careers' },
    '/blog': { type: 'CollectionPage', trail: 'Engineering Insights' },
    '/faq': { type: 'FAQPage', trail: 'Frequently Asked Questions' },
    '/legal': { type: 'CollectionPage', trail: 'Legal & Policies' },
  }

  const entry = simple[pathname]
  if (!entry) return null

  const pageNode = webPageNode({
    path: pathname,
    name: meta.title,
    description: meta.description,
    type: entry.type,
  })

  const nodes: unknown[] = [
    // FAQPage markup only where the questions are visibly rendered: on /faq the
    // page node itself is the FAQPage and carries the question list, so the
    // document never contains two competing FAQPage entities.
    pathname === '/faq'
      ? {
          ...pageNode,
          '@id': FAQ_NODE['@id'],
          mainEntity: FAQ_NODE.mainEntity,
        }
      : pageNode,
    breadcrumbNode([
      { name: 'Home', path: '/' },
      { name: entry.trail, path: pathname },
    ]),
  ]
  if (pathname === '/platform') {
    nodes.push(...SOFTWARE_APPLICATION_NODES)
  }
  if (pathname === '/work' || pathname === '/work/projects' || pathname === '/work/case-studies') {
    nodes.push(...SCENARIO_ARTICLE_NODES)
  }
  return nodes
}

/** Wrap any node list into a single `@graph` document. */
export function jsonLdDocument(nodes: readonly unknown[]) {
  return { '@context': 'https://schema.org', '@graph': nodes }
}
