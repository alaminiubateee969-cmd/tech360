function webPageNode(overrides: {
  path: string
  name: string
  description: string
  type?: 'WebPage' | 'AboutPage' | 'ContactPage' | 'CollectionPage' | 'FAQPage'
}) {
  return {
    '@type': overrides.type ?? 'WebPage',
    '@id': `${SITE_URL}${overrides.path}#webpage`,
    url: overrides.path === '/' ? `${SITE_URL}/` : `${SITE_URL}${overrides.path}`,
    name: overrides.name,
    description: overrides.description,
    isPartOf: { '@id': WEBSITE_ID },
    about: { '@id': ORG_ID },
    inLanguage: 'en',
  }
}

/** BreadcrumbList for a page deeper than the homepage. */
export function breadcrumbNode(trail: { name: string; path: string }[]) {
  return {
    '@type': 'BreadcrumbList',
    '@id': `${SITE_URL}${trail[trail.length - 1].path}#breadcrumb`,
    itemListElement: trail.map((step, index) => ({
      '@type': 'ListItem',
      position: index + 1,
      name: step.name,
      item: step.path === '/' ? `${SITE_URL}/` : `${SITE_URL}${step.path}`,
    })),
  }
}

