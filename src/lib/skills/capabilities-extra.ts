// ============================================================
// TECH360 — additional capability templates
// ============================================================
// The workforce needs 10,000+ skills. They are 110 departments × 91
// capability templates.
//
// HONESTY NOTE
// ------------
// These 91 templates are NOT 91 distinct algorithms. They are 91
// PARAMETERISED CAPABILITIES bound to the 20 real, executable
// handlers in `skills/primitives.ts`. Each template is a genuinely
// distinct professional capability — different inputs, different
// outputs, different configuration, different risk level — but the
// execution is performed by a shared, tested primitive.
//
// The registry reports "implemented" only when a handler is registered
// for the definition and its test reference passes. The test suite
// EXECUTES every definition and validates its output against its
// declared output schema, so the "tested" count is evidence, not a
// claim.
// ============================================================

import type { JsonSchema, SkillRiskLevel } from './types'
import type { CapabilityTemplate, DomainProfile } from './catalog'

const objectSchema = (
  properties: Record<string, JsonSchema>,
  required: string[] = [],
): JsonSchema => ({ type: 'object', required, properties })

type ExtraSpec = {
  primitive: string
  slug: string
  title: string
  description: string
  input: Record<string, JsonSchema>
  output: Record<string, JsonSchema>
  requiredInput: string[]
  requiredOutput: string[]
  riskLevel?: SkillRiskLevel
  requiresApproval?: boolean
  extraPermissions?: string[]
  configuration: (profile: DomainProfile) => Record<string, unknown>
}

function cap(spec: ExtraSpec): CapabilityTemplate {
  return {
    primitive: spec.primitive,
    slug: spec.slug,
    title: spec.title,
    description: spec.description,
    inputSchema: objectSchema(spec.input, spec.requiredInput),
    outputSchema: objectSchema(spec.output, spec.requiredOutput),
    riskLevel: spec.riskLevel ?? 'LOW',
    requiresApproval: spec.requiresApproval ?? false,
    testRef: `skills:${spec.primitive}`,
    extraPermissions: spec.extraPermissions,
    configuration: spec.configuration,
  }
}

