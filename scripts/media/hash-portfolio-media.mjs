#!/usr/bin/env node
/**
 * Writes src/data/portfolio-media-versions.ts — a content hash for every
 * portfolio media file, used to build versioned URLs (`/videos/work/x.mp4?v=<hash>`).
 *
 * WHY: portfolio media filenames are slug-based and replaceable
 * (re-rendering a video overwrites `<slug>.mp4`). Long-lived `immutable`
 * caching is only safe when the URL changes whenever the bytes change, so the
 * URL carries a SHA-256 prefix of the file content. next.config.ts applies
 * `immutable` caching ONLY to requests that carry `?v=`; unversioned requests
 * get a short revalidating policy.
 *
 * Run after adding or regenerating any portfolio media:
 *   node scripts/media/hash-portfolio-media.mjs
 * `tests/portfolio-media-cache.test.ts` fails if this file is stale.
 */
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..', '..')
const PUBLIC = join(ROOT, 'public')

/** Directories whose files are portfolio media. Keep in sync with next.config.ts. */
export const PORTFOLIO_MEDIA_DIRS = [
  'videos/work',
  'videos/work/posters',
  'images/case-studies/covers',
  'images/work/sm',
]

export function hashFile(file) {
  return createHash('sha256').update(readFileSync(file)).digest('hex').slice(0, 12)
}

export function collectVersions() {
  const versions = {}
  for (const dir of PORTFOLIO_MEDIA_DIRS) {
    const abs = join(PUBLIC, dir)
    for (const name of readdirSync(abs).sort()) {
      const file = join(abs, name)
      if (!statSync(file).isFile() || name.startsWith('.')) continue
      versions['/' + relative(PUBLIC, file).split('\\').join('/')] = hashFile(file)
    }
  }
  return versions
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const versions = collectVersions()
  const body = Object.entries(versions)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([path, hash]) => `  ${JSON.stringify(path)}: ${JSON.stringify(hash)},`)
    .join('\n')
  const out = `/**
 * GENERATED by scripts/media/hash-portfolio-media.mjs — do not edit by hand.
 * SHA-256 (first 12 hex chars) of each portfolio media file under public/.
 * Regenerate after replacing any file; tests/portfolio-media-cache.test.ts
 * fails when an entry no longer matches the bytes on disk.
 */
export const PORTFOLIO_MEDIA_VERSIONS: Readonly<Record<string, string>> = {
${body}
};
`
  writeFileSync(join(ROOT, 'src/data/portfolio-media-versions.ts'), out)
  console.log(`✓ wrote ${Object.keys(versions).length} media versions to src/data/portfolio-media-versions.ts`)
}
