#!/usr/bin/env node
/**
 * SFCC migration generator (development tooling).
 *
 * Produces the additive MySQL DDL for the `Factory*` control-plane models from
 * prisma/schema.prisma, and keeps scripts/mysql-schema-map.json in sync.
 * It is intentionally narrow: it only understands the scalar attributes used
 * by those models, and it refuses to emit anything for an unknown attribute.
 *
 *   node scripts/factory/gen-control-ddl.mjs            # write migration + map
 *   node scripts/factory/gen-control-ddl.mjs --check    # verify no drift
 *
 * The authoritative drift gate remains scripts/check-schema-drift.mjs.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const MIGRATION_DIR = join(ROOT, 'prisma', 'migrations', '14_software_factory_control_center')
const MIGRATION = join(MIGRATION_DIR, 'migration.sql')
const MAP = join(ROOT, 'scripts', 'mysql-schema-map.json')
const check = process.argv.includes('--check')

const schema = readFileSync(join(ROOT, 'prisma', 'schema.prisma'), 'utf8')
const blocks = [...schema.matchAll(/^model (Factory\w+) \{([\s\S]*?)^\}/gm)]

const TYPE = { String: 'VARCHAR(191)', Int: 'INTEGER', Boolean: 'BOOLEAN', DateTime: 'DATETIME(3)' }
const NATIVE = { Text: 'TEXT', LongText: 'LONGTEXT', LongBlob: 'LONGBLOB' }

const mapEntries = { LongText: [], Text: [], LongBlob: [] }
const tables = []

for (const [, name, body] of blocks) {
  const columns = []
  const indexes = []
  let primary = 'id'
  for (const raw of body.split('\n')) {
    const line = raw.trim()
    if (!line || line.startsWith('//')) continue
    if (line.startsWith('@@')) {
      const m = /^@@(index|unique)\(\[([^\]]+)\]/.exec(line)
      if (!m) continue
      const fields = m[2].split(',').map((f) => f.trim().split(':')[0].trim())
      indexes.push({ fields, unique: m[1] === 'unique', name: `${name}_${fields.join('_')}_${m[1] === 'unique' ? 'key' : 'idx'}` })
      continue
    }
    const f = /^(\w+)\s+(String|Int|Boolean|DateTime)(\?)?\s*(.*)$/.exec(line)
    if (!f) continue
    const [, field, prismaType, optional, rawAttrs] = f
    const attrs = rawAttrs.split('//')[0]
    const native = /@db\.(Text|LongText|LongBlob)/.exec(attrs)?.[1]
    if (native) mapEntries[native].push(`${name}.${field}`)
    const sqlType = native ? NATIVE[native] : TYPE[prismaType]
    const notNull = optional ? 'NULL' : 'NOT NULL'
    // Greedy to the last ')' on the attribute part: @default(now()) and
    // @default(cuid()) both contain an inner pair of parentheses.
    const def = /@default\((.*)\)/.exec(attrs)?.[1]?.trim()
    let sqlDefault = ''
    if (def && def !== 'cuid()' && def !== 'uuid()') {
      if (def === 'now()') sqlDefault = ' DEFAULT CURRENT_TIMESTAMP(3)'
      else if (/^"(.*)"$/.exec(def)) sqlDefault = ` DEFAULT '${/^"(.*)"$/.exec(def)[1]}'`
      else if (/^(true|false|-?\d+)$/.test(def)) sqlDefault = ` DEFAULT ${def}`
      else throw new Error(`Unsupported default for ${name}.${field}: ${def}`)
    }
    if (/@id\b/.test(attrs)) primary = field
    if (/@unique\b/.test(attrs)) indexes.push({ fields: [field], unique: true, name: `${name}_${field}_key` })
    columns.push(`    \`${field}\` ${sqlType} ${notNull}${sqlDefault}`)
  }
  for (const idx of indexes) {
    columns.push(`    ${idx.unique ? 'UNIQUE INDEX' : 'INDEX'} \`${idx.name}\`(${idx.fields.map((f) => `\`${f}\``).join(', ')})`)
  }
  columns.push(`    PRIMARY KEY (\`${primary}\`)`)
  tables.push(`-- CreateTable\nCREATE TABLE \`${name}\` (\n${columns.join(',\n')}\n) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;`)
}

const ddl = [
  '-- BDTECH360 — Software Factory Control Center (additive, no destructive change).',
  '-- Control-plane tables only; existing CRM/factory tables are untouched.',
  '-- No foreign keys are used: company/application identity is enforced in',
  '-- server-side access control, and records must survive source handover.',
  '-- Generated by scripts/factory/gen-control-ddl.mjs; verified by',
  '-- scripts/check-schema-drift.mjs and tests/schema-ddl-parity.test.ts.',
  '',
  ...tables,
  '',
].join('\n')

const map = JSON.parse(readFileSync(MAP, 'utf8'))
for (const kind of Object.keys(mapEntries)) {
  const existing = new Set(map[kind] ?? [])
  for (const key of mapEntries[kind]) existing.add(key)
  map[kind] = [...existing]
}
const mapOut = `${JSON.stringify(map, null, 2)}\n`

if (check) {
  const sameSql = existsSync(MIGRATION) && readFileSync(MIGRATION, 'utf8') === ddl
  const sameMap = readFileSync(MAP, 'utf8') === mapOut
  if (!sameSql || !sameMap) {
    console.error(`✗ control-plane DDL/map drift (sql=${sameSql}, map=${sameMap})`)
    process.exit(1)
  }
  console.log(`✓ control-plane DDL and native-type map in sync (${tables.length} tables)`)
  process.exit(0)
}

mkdirSync(MIGRATION_DIR, { recursive: true })
writeFileSync(MIGRATION, ddl)
writeFileSync(MAP, mapOut)
console.log(`Wrote ${tables.length} tables → ${MIGRATION}`)
console.log(`Wrote ${Object.values(mapEntries).flat().length} native-type map entries → ${MAP}`)
