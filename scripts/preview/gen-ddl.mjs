import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync(process.argv[2], 'utf8')

const scalar = new Map([
  ['String', 'TEXT'], ['Int', 'INTEGER'], ['BigInt', 'BIGINT'], ['Float', 'REAL'],
  ['Decimal', 'DECIMAL'], ['Boolean', 'BOOLEAN'], ['DateTime', 'DATETIME'],
  ['Json', 'JSON'], ['Bytes', 'BLOB'],
])

const models = []
const re = /^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm
let m
while ((m = re.exec(src))) models.push({ name: m[1], body: m[2] })
const modelNames = new Set(models.map((x) => x.name))

const q = (s) => `"${s}"`

function parseModel({ name, body }) {
  const fields = []
  const uniques = []
  const indexes = []
  let tableName = name
  for (const raw of body.split('\n')) {
    const line = raw.trim()
    if (!line || line.startsWith('//')) continue
    if (line.startsWith('@@map(')) { tableName = line.match(/"([^"]+)"/)[1]; continue }
    if (line.startsWith('@@unique')) { uniques.push(parseFieldList(line)); continue }
    if (line.startsWith('@@index')) { indexes.push(parseFieldList(line)); continue }
    if (line.startsWith('@@')) continue
    const parts = line.split(/\s+/)
    const fname = parts[0]
    const ftype = parts[1]
    if (!ftype) continue
    const isList = ftype.endsWith('[]')
    const base = ftype.replace(/[\[\]?]/g, '')
    if (isList || modelNames.has(base)) continue // relation, no column
    const sqlType = scalar.get(base)
    if (!sqlType) throw new Error(`unknown type ${base} in ${name}.${fname}`)
    const rest = line.slice(line.indexOf(ftype) + ftype.length)
    const isOptional = ftype.endsWith('?')
    const isId = /@id\b/.test(rest)
    const isUnique = /@unique\b/.test(rest) || isId
    let dflt = ''
    const dm = rest.match(/@default\(([^)]*(?:\([^)]*\))?[^)]*)\)/)
    if (dm) {
      const v = dm[1].trim()
      if (v === 'now()') dflt = ' DEFAULT CURRENT_TIMESTAMP'
      else if (v === 'true' || v === 'false' || /^-?\d+(\.\d+)?$/.test(v)) dflt = ` DEFAULT ${v}`
      else if (/^"/.test(v)) dflt = ` DEFAULT '${v.slice(1, -1).replace(/'/g, "''")}'`
      // cuid()/uuid() are generated by Prisma on the client — no SQL default
    }
    fields.push({
      name: fname,
      sql: `${q(fname)} ${sqlType}${isId ? ' NOT NULL' : isOptional ? '' : ' NOT NULL'}${dflt}`,
      isId,
      isUnique,
    })
  }
  return { name, tableName, fields, uniques, indexes }
}

function parseFieldList(line) {
  // @@unique([a, b], map: "name") -> ["a","b"]
  const start = line.indexOf('[')
  const end = line.indexOf(']')
  if (start === -1 || end === -1) return []
  const inner = line.slice(start + 1, end)
  return [...inner.matchAll(/(\w+)/g)].map((x) => x[1])
}

const statements = []
for (const model of models) {
  const { tableName, fields, uniques, indexes } = parseModel(model)
  const cols = fields.map((f) => f.sql)
  const pk = fields.filter((f) => f.isId).map((f) => q(f.name))
  if (pk.length) cols.push(`PRIMARY KEY (${pk.join(', ')})`)
  for (const f of fields) if (f.isUnique && !f.isId) cols.push(`UNIQUE (${q(f.name)})`)
  statements.push(`CREATE TABLE ${q(tableName)} (\n  ${cols.join(',\n  ')}\n);`)
  for (const u of uniques) statements.push(`CREATE UNIQUE INDEX ${q(`${tableName}_${u.join('_')}_key`)} ON ${q(tableName)} (${u.map(q).join(', ')});`)
  for (const i of indexes) statements.push(`CREATE INDEX ${q(`${tableName}_${i.join('_')}_idx`)} ON ${q(tableName)} (${i.map(q).join(', ')});`)
}

writeFileSync(process.argv[3], statements.join('\n') + '\n')
console.log(`DDL: ${models.length} tables, ${statements.length} statements`)
